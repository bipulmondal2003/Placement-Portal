import { BadRequestException, ConflictException, ForbiddenException, Injectable, NotFoundException } from '@nestjs/common';
import { InjectModel } from '@nestjs/mongoose';
import { Model, Types } from 'mongoose';
import { EvidenceItem, EvidenceItemDocument, Verification, VerificationDocument } from '../database/schemas/evidence.schema';
import { StudentProfile, StudentProfileDocument } from '../database/schemas/user.schema';
import { EvidenceSource, EvidenceStatus, EvidenceType, Role } from '../common/constants';
import { AuthUser } from '../common/decorators';
import { AuthorizationService } from '../authz/authz.service';
import { SkillsService } from '../skills/skills.service';
import { JobsService } from '../queues/jobs.service';
import { AuditService } from '../audit/audit.service';
import { CacheService } from '../redis/cache.service';
import { Page, paginate } from '../common/pagination';
import { FilesService } from '../files/files.service';

/** Evidence types a student may create by hand. Assessment / mock-interview evidence is created by the system only. */
export const STUDENT_SUBMITTABLE: EvidenceType[] = [EvidenceType.Academic, EvidenceType.Project, EvidenceType.Certification, EvidenceType.External];

export interface SubmitEvidenceInput {
  type: EvidenceType;
  title: string;
  description?: string;
  url?: string;
  /** Id of a certificate previously uploaded through POST /files/certificates (certification evidence only). */
  fileId?: string;
  skills: Array<{ skill: string; claimedLevel: number }>;
  meta?: Record<string, any>;
  source?: EvidenceSource;
}

export interface ReviewInput {
  decision: 'approved' | 'rejected';
  comment?: string;
  /** Optional per-skill awarded levels (capped at the claimed level). Defaults to the claimed level. */
  awarded?: Array<{ skill: string; level: number }>;
}

@Injectable()
export class EvidenceService {
  constructor(
    @InjectModel(EvidenceItem.name) private readonly evidence: Model<EvidenceItemDocument>,
    @InjectModel(Verification.name) private readonly verifications: Model<VerificationDocument>,
    @InjectModel(StudentProfile.name) private readonly profiles: Model<StudentProfileDocument>,
    private readonly authz: AuthorizationService,
    private readonly skills: SkillsService,
    private readonly jobs: JobsService,
    private readonly audit: AuditService,
    private readonly cache: CacheService,
    private readonly files: FilesService,
  ) {}

  async submit(student: AuthUser, input: SubmitEvidenceInput, ip?: string) {
    if (student.role !== Role.Student) throw new ForbiddenException('Only students submit evidence');
    if (!STUDENT_SUBMITTABLE.includes(input.type)) {
      throw new BadRequestException('Assessment and mock-interview evidence is generated by the system, not submitted manually');
    }
    if (!input.skills?.length) throw new BadRequestException('Link at least one skill to this evidence');
    const ids = input.skills.map((s) => s.skill);
    if (new Set(ids).size !== ids.length) throw new BadRequestException('Each skill may be claimed only once per evidence item');
    await this.skills.assertSkillsExist(ids);

    if (input.fileId && input.type !== EvidenceType.Certification) {
      throw new BadRequestException('Files can only be attached to certification evidence');
    }
    // The upload must be this student's own, unused certificate. Claimed again atomically below.
    const file = input.fileId ? await this.files.assertAttachable(student.id, input.fileId) : undefined;

    // Resume-extracted claims carry source=resume_ai and always start unverified, like everything else.
    const doc = await this.evidence.create({
      student: student.id,
      type: input.type,
      title: input.title,
      description: input.description,
      url: input.url,
      file,
      meta: input.meta,
      source: input.source === EvidenceSource.ResumeAi ? EvidenceSource.ResumeAi : EvidenceSource.Manual,
      status: EvidenceStatus.Pending,
      skills: input.skills.map((s) => ({ skill: s.skill, claimedLevel: s.claimedLevel })),
    });
    if (file && !(await this.files.attach(student.id, file.id, String(doc._id)))) {
      await this.evidence.deleteOne({ _id: doc._id });
      throw new ConflictException('This file was just attached to another evidence item');
    }
    await this.audit.log('evidence.submit', student, 'EvidenceItem', String(doc._id), { type: input.type }, ip);
    // The pending claim changes the student's profile (pending counters) but never their verified level.
    await this.jobs.requestRecalculation(student.id, ids, 'evidence_submitted');
    await this.cache.invalidate('dashboards');
    return doc;
  }

  /** Faculty review. Only the student's assigned mentor can verify; students can never verify their own evidence. */
  async review(reviewer: AuthUser, evidenceId: string, input: ReviewInput, ip?: string) {
    if (reviewer.role !== Role.Faculty) throw new ForbiddenException('Only faculty can verify evidence');
    if (!Types.ObjectId.isValid(evidenceId)) throw new NotFoundException('Evidence not found');
    const ev = await this.evidence.findById(evidenceId);
    if (!ev) throw new NotFoundException('Evidence not found');
    await this.authz.assertCanAccessStudent(reviewer, String(ev.student));
    if (String(ev.student) === reviewer.id) throw new ForbiddenException('You cannot verify your own evidence');
    if (ev.status !== EvidenceStatus.Pending) throw new ConflictException(`This evidence has already been ${ev.status}`);
    if (input.decision === 'rejected' && !input.comment?.trim()) throw new BadRequestException('A comment explaining the rejection is required');

    const awardedBySkill = new Map((input.awarded ?? []).map((a) => [a.skill, a.level]));
    for (const k of awardedBySkill.keys()) {
      if (!ev.skills.some((s) => String(s.skill) === k)) throw new BadRequestException('Awarded level references a skill that is not part of this evidence');
    }

    // Atomic status transition: only one concurrent reviewer wins.
    const awarded = ev.skills.map((s) => {
      const requested = awardedBySkill.get(String(s.skill));
      const level = input.decision === 'approved' ? Math.min(s.claimedLevel, Math.max(0, Math.min(5, requested ?? s.claimedLevel))) : 0;
      return { skill: s.skill, claimedLevel: s.claimedLevel, awardedLevel: level };
    });
    const res = await this.evidence.updateOne(
      { _id: ev._id, status: EvidenceStatus.Pending },
      {
        $set: {
          status: input.decision === 'approved' ? EvidenceStatus.Verified : EvidenceStatus.Rejected,
          skills: awarded,
          verifiedAt: new Date(),
          verifiedBy: reviewer.id,
        },
      },
    );
    if (!res.matchedCount) throw new ConflictException('This evidence was just reviewed by someone else');

    await this.verifications.create({
      evidence: ev._id,
      student: ev.student,
      reviewer: reviewer.id,
      decision: input.decision,
      comment: input.comment,
      awarded,
    });
    await this.audit.log(`evidence.${input.decision}`, reviewer, 'EvidenceItem', evidenceId, { student: String(ev.student) }, ip);
    await this.afterChange(String(ev.student), awarded.map((a) => String(a.skill)));
    return this.evidence.findById(evidenceId).lean();
  }

  /**
   * System-generated evidence (objective assessment scoring, interviewer-attested mock interviews).
   * Created already verified because the configured process (backend scoring / interviewer attestation)
   * is itself the review. Governed by SystemConfig flags in the callers.
   */
  async createSystemEvidence(args: {
    student: string;
    type: EvidenceType;
    title: string;
    description?: string;
    skills: Array<{ skill: string; level: number }>;
    verifiedBy?: string;
    meta?: Record<string, any>;
    autoVerify: boolean;
    comment?: string;
  }) {
    const verified = args.autoVerify;
    const doc = await this.evidence.create({
      student: args.student,
      type: args.type,
      title: args.title,
      description: args.description,
      source: EvidenceSource.System,
      status: verified ? EvidenceStatus.Verified : EvidenceStatus.Pending,
      meta: args.meta,
      verifiedAt: verified ? new Date() : undefined,
      verifiedBy: verified ? args.verifiedBy : undefined,
      skills: args.skills.map((s) => ({ skill: s.skill, claimedLevel: Math.max(1, s.level), awardedLevel: verified ? s.level : undefined })),
    });
    if (verified) {
      await this.verifications.create({
        evidence: doc._id,
        student: args.student,
        reviewer: args.verifiedBy,
        decision: args.verifiedBy ? 'approved' : 'system_approved',
        comment: args.comment ?? 'Verified by the configured process',
        awarded: doc.skills,
      });
    }
    await this.afterChange(args.student, args.skills.map((s) => s.skill));
    return doc;
  }

  private async afterChange(studentId: string, skillIds: string[]) {
    // Debounced, de-duplicated; falls back to inline recompute when Redis is down.
    await this.jobs.requestRecalculation(studentId, skillIds, 'evidence_change');
    await this.cache.invalidate('dashboards');
  }

  // ------------------------------------------------------------------ reads

  async listForStudent(user: AuthUser, studentId: string, q: { page: number; limit: number; status?: string; type?: string }): Promise<Page> {
    await this.authz.assertCanAccessStudent(user, studentId);
    const filter: Record<string, any> = { student: studentId };
    if (q.status) filter.status = q.status;
    if (q.type) filter.type = q.type;
    return paginate(this.evidence, filter, { page: q.page, limit: q.limit, populate: { path: 'skills.skill', select: 'name' } });
  }

  /** Faculty queue: pending evidence of the faculty member's own mentees only. */
  async queue(faculty: AuthUser, q: { page: number; limit: number; status?: string; type?: string }): Promise<Page> {
    const mentees = await this.authz.menteeIds(faculty.id);
    const filter: Record<string, any> = { student: { $in: mentees }, status: q.status ?? EvidenceStatus.Pending };
    if (q.type) filter.type = q.type;
    const page = await paginate(this.evidence, filter, {
      page: q.page,
      limit: q.limit,
      sort: { createdAt: 1 },
      populate: [
        { path: 'skills.skill', select: 'name' },
        { path: 'student', select: 'name email department' },
      ],
    });
    return page;
  }

  async getOne(user: AuthUser, id: string) {
    if (!Types.ObjectId.isValid(id)) throw new NotFoundException('Evidence not found');
    const ev = await this.evidence
      .findById(id)
      .populate('skills.skill', 'name')
      .populate('student', 'name email department')
      .lean();
    if (!ev) throw new NotFoundException('Evidence not found');
    const studentId = String((ev.student as any)._id ?? ev.student);
    await this.authz.assertCanAccessStudent(user, studentId);
    const history = await this.verifications.find({ evidence: id }).sort({ createdAt: 1 }).populate('reviewer', 'name').lean();
    return { ...ev, history };
  }

  /** Verification history (decisions made), scoped by role. */
  async history(user: AuthUser, q: { page: number; limit: number }) {
    const filter: Record<string, any> = {};
    if (user.role === Role.Faculty) filter.reviewer = user.id;
    else if (user.role === Role.Student) filter.student = user.id;
    return paginate(this.verifications, filter, {
      page: q.page,
      limit: q.limit,
      populate: [
        { path: 'evidence', select: 'title type' },
        { path: 'student', select: 'name' },
        { path: 'reviewer', select: 'name' },
      ],
    });
  }

  /** Withdraw a still-pending submission (students only, own evidence). */
  async withdraw(student: AuthUser, id: string) {
    if (!Types.ObjectId.isValid(id)) throw new NotFoundException('Evidence not found');
    const ev = await this.evidence.findOne({ _id: id, student: student.id });
    if (!ev) throw new NotFoundException('Evidence not found');
    if (ev.status !== EvidenceStatus.Pending) throw new ConflictException('Only pending evidence can be withdrawn');
    await ev.deleteOne();
    await this.files.deleteForEvidence(id);
    await this.afterChange(student.id, ev.skills.map((s) => String(s.skill)));
    return { ok: true };
  }
}
